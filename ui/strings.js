// Headings with a sort arrow ("Asked in ↓"): translate the text, keep the arrow.
const ARROW = /^(.*\S) ([↑↓])$/;

function trText(s){
  if (lang === "en" || !s) return s;
  const lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0], core = s.trim();
  if (!core) return s;
  const e = TR[core];
  if (e && e[lang]) return lead + e[lang] + trail;
  const a = ARROW.exec(core);
  if (a && TR[a[1]] && TR[a[1]][lang]) return lead + TR[a[1]][lang] + " " + a[2] + trail;
  for (const [rx, de, id] of TRP){
    const out = lang === "de" ? de : id;
    // Captured parts that are themselves known texts ("Submit today") are translated too.
    if (out && rx.test(core)) return lead + core.replace(rx, (...m) => out.replace(/\$(\d)/g, (_, i) => { const g = m[+i] || ""; return (TR[g] && TR[g][lang]) || g; })) + trail;
  }
  return s;
}

// Original English text per node/attribute, so switching back to English (or to another language) works live.
// LAST remembers what this file wrote, so its own changes are not mistaken for new text from the app.
const ORIG = new WeakMap(), LAST = new WeakMap();
const ATTRS = ["title", "placeholder", "aria-label"];
function trNode(n){
  if (n.nodeType === 3){
    const p = n.parentElement;
    if (!p || p.closest("script,style,[data-notr],.updbody,textarea")) return;
    if (!ORIG.has(n) || (LAST.has(n) && n.nodeValue !== LAST.get(n))) ORIG.set(n, n.nodeValue);
    const want = trText(ORIG.get(n));
    LAST.set(n, want);
    if (n.nodeValue !== want) n.nodeValue = want;
    return;
  }
  if (n.nodeType !== 1 || n.closest("[data-notr]")) return;
  let o = ORIG.get(n), last = LAST.get(n);
  for (const a of ATTRS){
    if (!n.hasAttribute(a)) continue;
    if (!o){ o = {}; ORIG.set(n, o); }
    if (!last){ last = {}; LAST.set(n, last); }
    const cur = n.getAttribute(a);
    if (!(a in o) || (a in last && cur !== last[a])) o[a] = cur;
    const want = trText(o[a]);
    last[a] = want;
    if (cur !== want) n.setAttribute(a, want);
  }
}
function trTree(root){
  if (!root) return;
  trNode(root);
  if (root.nodeType === 1){
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    while (w.nextNode()) trNode(w.currentNode);
  }
}
// New or changed content is translated as it appears (renders, toasts, dialogs, drawers).
const trObs = new MutationObserver((muts) => {
  for (const m of muts){
    if (m.type === "childList") m.addedNodes.forEach(trTree);
    else trNode(m.target);
  }
  trObs.takeRecords();  // drop the records caused by the translation itself
});
function startTranslation(){
  trTree(document.body);
  trObs.observe(document.body, {subtree:true, childList:true, characterData:true, attributes:true, attributeFilter:ATTRS});
}
